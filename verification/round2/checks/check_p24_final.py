#!/usr/bin/env python3
"""Input: p24_prufer_definition.cpp. No submitted code is imported.

Run: python3 check_p24_final.py
Output: P24_PRUFER_AUDIT.json and stdout. Requires clang++/g++.

All labelled trees of orders 3..9 are generated by Prüfer words, and
domination/criticality is checked directly from adjacency and subsets.
Uses integer cross-products for rational comparisons. Records n=3,4 too.
"""
import json, pathlib, subprocess
HERE=pathlib.Path(__file__).resolve().parent
BIN=pathlib.Path('/tmp/fv2_p24_prufer_definition')
subprocess.run(['c++','-O3','-std=c++17',str(HERE/'p24_prufer_definition.cpp'),'-o',str(BIN)],check=True)
output=subprocess.check_output([str(BIN),'9'],text=True)
rows=[json.loads(x) for x in output.strip().splitlines()]
assert [r['n'] for r in rows]==list(range(3,10))
assert all(r['trees']==r['n']**(r['n']-2) for r in rows)
for r in rows:
    assert all(r[x]==0 for x in ['inequality_violations','star_false_positives','star_false_negatives','top_count_violations','last_step_violations','gamma_bound_violations'])
    assert r['equalities']==r['stars']==r['n']
result={'type':'direct_definition_Prufer_exhaustion','orders':rows,
        'total_labelled_trees':sum(r['trees'] for r in rows),
        'overall':'pass','note':'Exact rational arithmetic; no recurrence or manuscript leaf formula used.'}
(HERE/'P24_PRUFER_AUDIT.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
print(output,end='')
print('P24_PRUFER_OK trees='+str(result['total_labelled_trees'])+' orders=3..9')
